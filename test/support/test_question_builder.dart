import 'package:upsc_wars/core/domain/entities/test_question.dart';

/// Minimal [TestQuestion] for unit tests (battle, confidence, filters).
TestQuestion buildTestQuestion({
  required String uuid,
  String subject = 'ancient_history',
  String topic = 'Indus Valley',
  bool negativeFraming = false,
  String? questionType = 'direct',
  String? trapType,
  String correctOption = 'a',
  String? selectedOption,
  String status = 'unattempted',
  String? confidence,
}) {
  return TestQuestion(
    uuid: uuid,
    subject: subject,
    topic: topic,
    negativeFraming: negativeFraming,
    displayText: 'Q $uuid',
    displayTextHi: 'Q $uuid',
    optionA: 'A',
    optionAHi: 'A',
    optionB: 'B',
    optionBHi: 'B',
    optionC: 'C',
    optionCHi: 'C',
    optionD: 'D',
    optionDHi: 'D',
    correctOption: correctOption,
    questionType: questionType,
    trapType: trapType,
    hasTable: false,
    tableData: null,
    tableDataHi: null,
    position: 1,
    selectedOption: selectedOption,
    status: status,
    flagged: false,
    timeSpentSecs: null,
    confidence: confidence,
    conceptAnchor: null,
    finalExplanation: null,
    finalExplanationHi: null,
    eliminationLogic: const [],
    eliminationLogicHi: const [],
    statementAnalysis: const [],
    statementAnalysisHi: const [],
    strongDistractor: null,
    strongDistractorHi: null,
    upscTrapExplanation: null,
    upscTrapExplanationHi: null,
    conceptsUsed: const [],
  );
}
